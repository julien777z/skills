TYPESCRIPT_TYPES: Final[dict[Callable[..., object], str]] = {
    check_text: "string",
    check_timestamp: "string",
    check_texts: "string[]",
    check_rows: "string[][]",
    check_fraction: "number",
    check_whole_number: "number",
    check_sections: "Section[]",
}


def typescript_type(check: Callable[[object, str], object]) -> str:
    """Return the TypeScript type a field's check accepts."""

    if not isinstance(check, partial):
        return TYPESCRIPT_TYPES[check]

    match check.func:
        case func if func is check_choice:
            return check.keywords["choices"].__name__
        case func if func is check_object:
            return check.keywords["shape"]["name"]
        case _:
            return f"{check.keywords['shape']['name']}[]"


def typescript_interface(shape: ObjectShape, section_type: SectionType | None = None) -> str:
    """Return the TypeScript interface for one spec object."""

    lines = [f"export interface {shape['name']} {{"]

    for key, check in shape["fields"].items():
        optional = "" if key in shape["required"] else "?"
        field_type = f"typeof SectionType.{section_type.name}" if section_type and key == "type" else typescript_type(check)

        lines.append(f"  {key}{optional}: {field_type};")

    return "\n".join([*lines, "}"])


def typescript_enum(choices: type[StrEnum]) -> str:
    """Return a string enum as a TypeScript const object and its union type."""

    members = "\n".join(f"  {choice.name}: '{choice.value}'," for choice in choices)

    return f"export const {choices.__name__} = {{\n{members}\n}} as const;\n\nexport type {choices.__name__} = (typeof {choices.__name__})[keyof typeof {choices.__name__}];"


def referenced_declarations(shape: ObjectShape, shapes: dict[str, ObjectShape], enums: dict[str, type[StrEnum]]) -> None:
    """Collect the shapes and enums a shape's fields refer to, each after what it refers to."""

    for check in shape["fields"].values():
        if not isinstance(check, partial):
            continue

        if "choices" in check.keywords:
            enums.setdefault(check.keywords["choices"].__name__, check.keywords["choices"])
        elif check.keywords["shape"]["name"] not in shapes:
            referenced_declarations(check.keywords["shape"], shapes, enums)

    shapes.setdefault(shape["name"], shape)


def typescript_declarations() -> str:
    """Return the dashboard spec's TypeScript declarations, generated from its shapes."""

    shapes: dict[str, ObjectShape] = {}
    enums: dict[str, type[StrEnum]] = {SectionType.__name__: SectionType}

    for section in SECTION_SHAPES.values():
        referenced_declarations(section, shapes, enums)

    referenced_declarations(DASHBOARD_SHAPE, shapes, enums)

    section_names = {shape["name"]: section_type for section_type, shape in SECTION_SHAPES.items()}
    union = " | ".join(section_names)
    interfaces = [typescript_interface(shape, section_names.get(name)) for name, shape in shapes.items()]
    page_index = next(index for index, name in enumerate(shapes) if name == PAGE_SHAPE["name"])
    blocks = [
        *(typescript_enum(choices) for choices in enums.values()),
        *interfaces[:page_index],
        f"export type Section = {union};",
        *interfaces[page_index:],
    ]

    return TYPES_HEADER + "\n" + "\n\n".join(blocks) + "\n"


def embed_dashboard_spec(spec: dict[str, object]) -> str:
    """Serialize the spec for embedding in a script element."""

    serialized = dumps(spec, ensure_ascii=False, indent=2)

    return serialized.replace("&", "\\u0026").replace("<", "\\u003c").replace(">", "\\u003e")


def app_digest(declarations: str) -> str:
    """Return one digest over the app's source files and its generated declarations."""

    digest = sha256(declarations.encode("utf-8"))
    sources = sorted(
        path for path in APP_ROOT.rglob("*") if path.is_file() and not set(APP_BUILD_OUTPUTS).intersection(path.relative_to(APP_ROOT).parts)
    )

    for path in sources:
        digest.update(str(path.relative_to(APP_ROOT)).encode("utf-8"))
        digest.update(path.read_bytes())

    return digest.hexdigest()[:16]


def run_npm(arguments: list[str], workspace: Path) -> None:
    """Run one npm command in the build workspace."""

    npm = shutil.which("npm")

    if npm is None:
        raise DashboardBuildError("building the dashboard needs Node.js 20 or newer and npm on PATH")

    result = subprocess.run([npm, *arguments], cwd=workspace, capture_output=True, text=True, check=False)

    if result.returncode != 0:
        raise DashboardBuildError(f"npm {' '.join(arguments)} failed:\n{result.stdout}{result.stderr}")


def install_dependencies(workspace: Path) -> None:
    """Install the app's locked dependencies unless a finished install is already there."""

    if (workspace / INSTALL_MARKER).exists():
        return

    run_npm(["ci", "--no-audit", "--no-fund", "--loglevel=error"], workspace)

    (workspace / INSTALL_MARKER).touch()


def remove_path(path: Path) -> None:
    """Delete a file or a directory tree."""

    if path.is_dir():
        shutil.rmtree(path)
    else:
        path.unlink()


def build_page() -> str:
    """Return the built dashboard page, building the app the first time its source changes."""

    declarations = typescript_declarations()
    page_path = CACHE_ROOT / f"page-{app_digest(declarations)}.html"
    workspace = CACHE_ROOT / f"workspace-{sha256((APP_ROOT / APP_LOCKFILE).read_bytes()).hexdigest()[:16]}"

    CACHE_ROOT.mkdir(parents=True, exist_ok=True)

    with (CACHE_ROOT / ".lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)

        if page_path.exists():
            return page_path.read_text(encoding="utf-8")

        logger.info("use-dashboard: building the dashboard app, which takes a minute the first time")

        workspace.mkdir(exist_ok=True)

        for entry in workspace.iterdir():
            if entry.name != "node_modules":
                remove_path(entry)

        shutil.copytree(APP_ROOT, workspace, ignore=shutil.ignore_patterns(*APP_BUILD_OUTPUTS), dirs_exist_ok=True)
        (workspace / APP_TYPES_PATH).write_text(declarations, encoding="utf-8")

        install_dependencies(workspace)

        run_npm(["run", "build"], workspace)

        page = (workspace / "dist" / "index.html").read_text(encoding="utf-8")
        partial_path = page_path.with_suffix(".partial")

        partial_path.write_text(page, encoding="utf-8")
        partial_path.replace(page_path)

        for stale in [*CACHE_ROOT.glob("page-*"), *CACHE_ROOT.glob("workspace-*")]:
            if stale not in (page_path, workspace):
                remove_path(stale)

        return page


def render_dashboard(spec: object, fragment: bool) -> str:
    """Return the dashboard page for a spec."""

    dashboard = check_object(spec, "dashboard", DASHBOARD_SHAPE)

    head = PAGE_HEAD_TEMPLATE.format(title=escape(str(dashboard["title"])))
    page = head + build_page().replace(DATA_PLACEHOLDER, embed_dashboard_spec(dashboard), 1)

    return page if fragment else DOCUMENT_PREAMBLE + page


def main() -> int:
    """Render a dashboard spec into an HTML page, or write the app's spec declarations."""

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    parser = ArgumentParser(description="Render a dashboard spec into an HTML page")
    commands = parser.add_mutually_exclusive_group(required=True)

    commands.add_argument("--input", type=Path, help="dashboard spec JSON file")
    commands.add_argument("--types", action="store_true", help=f"write the app's {APP_TYPES_PATH} for type-checking it")
    parser.add_argument("--output", type=Path, help="HTML file to write")
    parser.add_argument(
        "--fragment",
        action="store_true",
        help="omit the document preamble, for hosts that wrap the page in their own document",
    )

    arguments = parser.parse_args()

    if arguments.types:
        (APP_ROOT / APP_TYPES_PATH).write_text(typescript_declarations(), encoding="utf-8")

        return 0

    if arguments.output is None:
        parser.error("--input needs --output")

    try:
        page = render_dashboard(loads(arguments.input.read_text(encoding="utf-8")), arguments.fragment)
        encoded_page = page.encode("utf-8")
    except (OSError, JSONDecodeError, UnicodeError, DashboardSpecError, DashboardBuildError) as error:
        logger.error("use-dashboard: %s", error)

        return 1

    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_bytes(encoded_page)

    logger.info("%s", arguments.output.resolve())

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
